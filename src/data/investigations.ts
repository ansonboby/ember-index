export type Pillar = "prevention" | "detection" | "suppression";
export type FuelType = "solid" | "liquid" | "gas";

export interface Investigation {
  id: string;
  name: string;
  fullName: string;
  years: string;
  lastYear: number;
  status: "completed" | "upcoming";
  platform: string;
  hardware: string;
  gravity: string;
  fuelSummary: string;
  fuelTypes: FuelType[];
  o2Min: number | null;
  o2Max: number | null;
  pressurePsi: number | null;
  flowSummary: string;
  sensors: string[];
  pillarRelevance: Record<Pillar, number>; // curated 0..1 strength per fire-safety pillar
  curatedRelevance: number; // curated 0..1 overall relevance to spacecraft fire safety
  objective: string;
  findings: string[];
  psiId: string | null; // filled during verification pass
  verified: boolean;
  note?: string;
}

export interface MissionProfile {
  id: string;
  name: string;
  o2: number; // % oxygen
  psi: number; // pressure, psi
  gravity: "micro" | "partial" | "earth";
  note: string;
}

