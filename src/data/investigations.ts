// Ember Index — curated dataset of NASA PSI microgravity combustion investigations.
// Every entry is to be verified field-by-field against its PSI page during the
// verification pass; `verified` is false until that happens. Numeric values taken
// from the challenge brief are reliable; others are flagged with `note`.

export type Pillar = "prevention" | "detection" | "suppression";
export type FuelType = "solid" | "liquid" | "gas";

export interface Investigation {
  id: string;
  name: string;
  fullName: string;
  years: string;
  lastYear: number;
  status: "completed" | "upcoming";
  platform: string;
  hardware: string;
  gravity: string;
  fuelSummary: string;
  fuelTypes: FuelType[];
  o2Min: number | null;
  o2Max: number | null;
  pressurePsi: number | null;
  flowSummary: string;
  sensors: string[];
  pillarRelevance: Record<Pillar, number>; // curated 0..1 strength per fire-safety pillar
  curatedRelevance: number; // curated 0..1 overall relevance to spacecraft fire safety
  objective: string;
  findings: string[];
  psiId: string | null; // verified against PSI search API (geode-py)
  doi: string | null; // persistent identifier, verified from PSI record
  verified: boolean; // identity/objective fields verified against PSI record
  note?: string;
}

export interface MissionProfile {
  id: string;
  name: string;
  o2: number; // % oxygen
  psi: number; // pressure, psi
  gravity: "micro" | "partial" | "earth";
  note: string;
}

